const byId=new Map(referenceCatalog.map(p=>[p.id,p]));
export function catalogProduct(row,now=Date.now()){
 const info=byId.get(row.id);if(!info)return {...row,format:'paper',unit:'cuốn',orderable:true};
 const activePromotion=!!info.old_price_vnd&&now<=Date.parse(info.promotion_ends_at)&&row.price_vnd===info.price_vnd;
 let price=info.price_vnd===null?null:row.price_vnd;
 if(info.old_price_vnd&&!activePromotion&&price===info.price_vnd)price=info.old_price_vnd;
 return {...row,format:info.format,format_label:info.format_label,unit:info.unit,pages:info.pages,groups:info.groups,previews:info.previews,price_vnd:price,old_price_vnd:activePromotion?info.old_price_vnd:null,promotion_ends_at:activePromotion?info.promotion_ends_at:null,badge:activePromotion?info.badge:info.old_price_vnd?'':info.badge,free_shipping_preorder:info.free_shipping_preorder,orderable:info.format==='paper'&&Number.isSafeInteger(price)&&price>0};
}
export function shippingFor(items,policy){
 return items.length&&items.every(i=>i.product.free_shipping_preorder)?0:policy.shipping_vnd;
}
